#include <stdio.h>
#include <math.h>
#include <stdlib.h>

int main() {
    double S;  // Площадь поверхности шара
    double R;  // Радиус шара
    double V;  // Объем шара
    const double PI = 3.14159265358979323846;
    
    // Ввод площади поверхности
    printf("Введите площадь поверхности шара (S): ");
    if (scanf("%lf", &S) != 1) {
        printf("Ошибка: некорректный ввод!\n");
        return 1;
    }
    
    // Проверка на корректность ввода
    if (S <= 0) {
        printf("Ошибка: площадь поверхности должна быть положительным числом!\n");
        return 1;
    }
    
    // Вычисление радиуса из площади поверхности
    R = sqrt(S / (4 * PI));
    
    // Вычисление объема
    V = (4.0 / 3.0) * PI * R * R * R;
    
    // Вывод результатов
    printf("\nРезультаты вычислений:\n");
    printf("Площадь поверхности: %.4f\n", S);
    printf("Радиус шара: %.4f\n", R);
    printf("Объем шара: %.4f\n", V);
    
    // Пауза для просмотра результата
    system("pause");
    
    return 0;
}